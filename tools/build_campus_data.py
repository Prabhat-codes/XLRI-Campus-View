"""Split phone numbers out of the public site.

Source of truth (private, never deployed):  tools/private/campus.json
  { "placePhones": { "<place name>": {"phone": "...", "phoneLabel": "..."} }, "contacts": [ full contact records ] }
Outputs:
  site/data/places.json    - same places, no phone numbers
  site/data/contacts.json  - roles, places and tags only (no names, no numbers)
  tools/apps_script/CampusData.gs - CAMPUS_DATA for the sheet script; served only with the campus code
Run:  python tools/build_campus_data.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRIV = os.path.join(ROOT, "tools", "private", "campus.json")
places_p = os.path.join(ROOT, "site", "data", "places.json")
contacts_p = os.path.join(ROOT, "site", "data", "contacts.json")

places = json.load(open(places_p, encoding="utf8"))
if not os.path.exists(PRIV):   # first run: lift numbers out of the current public files
    full = json.load(open(contacts_p, encoding="utf8"))["contacts"]
    phones = {p["name"]: {"phone": p["phone"], **({"phoneLabel": p["phoneLabel"]} if p.get("phoneLabel") else {})} for p in places["places"] if p.get("phone")}
    json.dump({"placePhones": phones, "contacts": full}, open(PRIV, "w", encoding="utf8"), ensure_ascii=False, indent=1)
priv = json.load(open(PRIV, encoding="utf8"))

for p in places["places"]:
    p.pop("phone", None); p.pop("phoneLabel", None)
    if p["name"] in priv["placePhones"]: p["hasPhone"] = True
json.dump(places, open(places_p, "w", encoding="utf8"), ensure_ascii=False, indent=2)

public = [{"role": c["role"], "place": c["place"], "tags": c["tags"]} for c in priv["contacts"]]
json.dump({"_note": "Public list of campus support roles. Names and numbers are only served to the campus version.", "contacts": public},
          open(contacts_p, "w", encoding="utf8"), ensure_ascii=False, indent=1)

gs = "// Generated by tools/build_campus_data.py. Do not edit by hand: edit tools/private/campus.json and re-run.\n"
gs += "const CAMPUS_DATA = " + json.dumps(priv, ensure_ascii=False, indent=1) + ";\n"
open(os.path.join(ROOT, "tools", "apps_script", "CampusData.gs"), "w", encoding="utf8").write(gs)
print(len(priv["placePhones"]), "place numbers and", len(priv["contacts"]), "contacts moved to the private file")
